# Print the following list using while loop
# [1,4,9,16,25,36,49,64,81,100]

sqr = [1, 4, 9, 16, 25, 36, 49, 64, 81, 100]

i = 0
while i<len(sqr):
    print(sqr[i])
    i+=1



# Above Program by for Loop

sqr = [1, 4, 9, 16, 25, 36, 49, 64, 81, 100]

for num in sqr:
    print(num)


