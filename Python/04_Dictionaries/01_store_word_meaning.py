# Store the following Words Meanings in Python's Dictionary

# table : "a piece of furniture" , "list of facts and figures"
#  cat : "a small animal"

dict = {
    "table" : ["a piece of furniture" , "list of facts and figures"],     # Two meanings of table stored in a list
    "cat" : "a small animal"
}

print(dict)     # {'table': ['a piece of furniture', 'list of facts and figures'], 'cat': 'a small animal'}