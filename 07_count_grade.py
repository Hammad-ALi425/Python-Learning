# Count number of Students with Grade 'A' in following tuple
# ("C", "D", "A", "A", "B", "A")
grade = ("C", "D", "A", "A", "B", "A")
counted_tuple = grade.count("A")                               # It can count How many times value appear in list.
print("The Students with Grade 'A' are: " , counted_tuple)     # The Students with Grade 'A' are:  3